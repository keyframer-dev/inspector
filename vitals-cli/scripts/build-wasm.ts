/**
 * Builds the symbols crate (inspector/symbols) to WebAssembly and writes what src/symbols.ts loads,
 * into src/symbolsWasm/ (the same pattern as react-native/scripts/build-core.ts):
 *   glue.js, glue.d.ts   wasm-bindgen's loader (--target web: works in Node 18+)
 *   bytes.ts             the module itself, base64, so dist/cli.js carries it with no file to find
 *
 *   bun scripts/build-wasm.ts            cargo build (release) + wasm-bindgen + wasm-opt
 *   bun scripts/build-wasm.ts --check    only report the size of what is there
 *
 * Needs rustup's toolchain with the wasm32-unknown-unknown target, wasm-bindgen-cli 0.2.100 (what
 * the crate pins) and, optionally, wasm-opt. The generated files are kept in the repository, so
 * building or testing the package needs none of this: run it after changing the Rust. It deletes
 * the crate's target/ afterwards unless --keep-target is passed (cargo output is large).
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import path from 'node:path'
import { gzipSync } from 'node:zlib'

const CRATE = path.resolve(import.meta.dir, '../../symbols')
const OUT = path.resolve(import.meta.dir, '../src/symbolsWasm')
const CARGO_BIN = path.join(homedir(), '.cargo/bin')
// rustup's cargo first: a Homebrew cargo has no wasm32 standard library.
const env = { ...process.env, PATH: `${CARGO_BIN}:${process.env.PATH}` }

const kb = (n: number) => `${(n / 1024).toFixed(1)} KB`

function run(cmd: string[], cwd = CRATE) {
  const r = Bun.spawnSync(cmd, { cwd, env, stdout: 'inherit', stderr: 'inherit' })
  if (r.exitCode !== 0) {
    console.error(`build-wasm: ${cmd.join(' ')} failed`)
    process.exit(1)
  }
}

function report() {
  const b64 = readFileSync(path.join(OUT, 'bytes.ts'), 'utf8').match(/'([A-Za-z0-9+/=]+)'/)?.[1] ?? ''
  const wasm = Buffer.from(b64, 'base64')
  console.log(`  symbols wasm  ${kb(wasm.length)} (gzipped ${kb(gzipSync(wasm, { level: 9 }).length)}), ${kb(b64.length)} as base64`)
}

if (process.argv.includes('--check')) {
  report()
  process.exit(0)
}

run(['cargo', 'build', '-p', 'keyframer-vitals-symbols-wasm', '--target', 'wasm32-unknown-unknown', '--release'])
const built = path.join(CRATE, 'target/wasm32-unknown-unknown/release/keyframer_vitals_symbols_wasm.wasm')
const tmp = path.join(tmpdir(), `keyframer-symbols-${process.pid}`)
rmSync(tmp, { recursive: true, force: true })
run(['wasm-bindgen', '--target', 'web', '--out-dir', tmp, '--out-name', 'glue', built])
let wasmFile = path.join(tmp, 'glue_bg.wasm')
const opt = Bun.spawnSync(['wasm-opt', '--version'], { env, stdout: 'ignore', stderr: 'ignore' })
if (opt.exitCode === 0) {
  const out = path.join(tmp, 'opt.wasm')
  run(['wasm-opt', '-Oz', '--converge', '--enable-bulk-memory', '--enable-nontrapping-float-to-int', '--enable-sign-ext', '--enable-mutable-globals', wasmFile, '-o', out], tmp)
  wasmFile = out
} else {
  console.log('  (wasm-opt not found: the module is not post-optimized; `cargo install wasm-opt`)')
}

const header = '/* eslint-disable */\n// Generated by scripts/build-wasm.ts from inspector/symbols (wasm-bindgen). Do not edit.\n'
// The loader's default fetches a .wasm next to itself; symbols.ts always hands it the bytes.
const glue = readFileSync(path.join(tmp, 'glue.js'), 'utf8').replace(/new URL\('glue_bg\.wasm', import\.meta\.url\)/, "(() => { throw new Error('keyframer-vitals: pass the wasm bytes') })()")
mkdirSync(OUT, { recursive: true })
writeFileSync(path.join(OUT, 'glue.js'), header + glue)
// Typed by hand: wasm-bindgen's own declarations need the DOM library (RequestInfo, Response).
writeFileSync(
  path.join(OUT, 'glue.d.ts'),
  `${header}/** The objects in a Mach-O (thin or fat) or ELF file, as JSON. */
export function inspect(bytes: Uint8Array): string
/** The Swift mangled names object \`index\` uses, as a JSON array. */
export function swiftNames(bytes: Uint8Array, index: number): string
export function buildNative(bytes: Uint8Array, index: number, options: string): Built
export function buildR8(text: string, options: string): Built
export function buildSites(text: string, options: string): Built
/** The crate's name and version, as JSON. */
export function about(): string
/** A built symbol set: the manifest and its chunks as JSON. Free it when done. */
export class Built {
  manifest(): string
  /** What was skipped while reading the input, as a JSON array of strings. */
  warnings(): string
  chunkCount(): number
  chunkFile(i: number): string
  chunkJson(i: number): string
  free(): void
}
/** Instantiates the module from its bytes, synchronously. */
export function initSync(module: { module: unknown }): unknown
`,
)
const wasm = readFileSync(wasmFile)
writeFileSync(path.join(OUT, 'bytes.ts'), `${header}/** keyframer-vitals-symbols, built to WebAssembly: ${wasm.length} bytes, base64. */\nexport default '${wasm.toString('base64')}'\n`)
rmSync(tmp, { recursive: true, force: true })
if (!existsSync(path.join(OUT, 'bytes.ts'))) process.exit(1)
if (!process.argv.includes('--keep-target')) rmSync(path.join(CRATE, 'target'), { recursive: true, force: true })
report()
